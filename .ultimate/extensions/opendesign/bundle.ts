/**
 * The pure parts of a design pull: what a pulled design is called, which entry it shows, which file names may be
 * written and where, the manifest a pull leaves behind, and what changed since the pull before it. `server.ts` fetches
 * the files from OpenDesign's daemon and calls these.
 */

import { createHash } from 'node:crypto'
import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises'
import { dirname, join, resolve, sep } from 'node:path'

/** The snapshot's index, written next to the pulled files. */
export const manifestName = 'design.json'
/** The pulled frame: one PNG of the design as OpenDesign renders it, when the daemon can render one. */
export const frameName = 'frame.png'
/** The manifest's own warning, so nobody hand-edits a snapshot the next pull overwrites. */
export const generatedLine =
  'Generated by the opendesign extension from OpenDesign — do not edit; pull again instead.'

/** A file that goes into a pull, already fetched. */
export interface PulledFile {
  path: string
  mime: string
  bytes: Buffer
}

/** One file the manifest lists. */
export interface FileRecord {
  path: string
  mime: string
  size: number
  sha256: string
}

/** A file the daemon lists but this pull left out, and why. */
export interface SkippedFile {
  path: string
  reason: string
}

/** `designs/<slug>/design.json`: what this snapshot is and where it came from. */
export interface Manifest {
  generated: string
  project: { id: string; name: string; designSystemId: string | null }
  source: string
  fetchedAt: string
  entry: string | null
  frame: string | null
  frameError?: string
  files: FileRecord[]
  skipped: SkippedFile[]
}

/** What a pull wrote and removed, against the manifest it replaced. */
export interface ChangeSet {
  added: string[]
  changed: string[]
  removed: string[]
  unchanged: number
}

/** A design folder already in the project, as the panel lists it. */
export interface PulledDesign {
  dir: string
  slug: string
  projectId: string
  projectName: string
  fetchedAt: string
  files: number
}

/** A project the daemon knows, before a pull named its folder. */
export interface DesignProject {
  id: string
  name: string
}

const slugLimit = 48

/** A project's folder name under `designs/`: its name in lowercase ASCII, or its id when the name leaves nothing. */
export function slugOf(project: DesignProject): string {
  const ascii = project.name
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, slugLimit)
    .replace(/-+$/, '')
  return ascii || `design-${project.id.replace(/[^a-zA-Z0-9]/g, '').slice(0, 8)}`
}

/**
 * `raw` as a path inside a design folder, or `undefined` when it must not be written there: absolute, escaping with
 * `..`, carrying a NUL, or empty. Windows separators count as separators, so `..\..\x` is refused like `../../x`.
 */
export function relativePath(raw: unknown): string | undefined {
  if (typeof raw !== 'string') return undefined
  const text = raw.trim().replace(/\\/g, '/')
  if (!text || text.startsWith('/') || /^[a-zA-Z]:/.test(text) || text.includes('\0'))
    return undefined
  const segments = text.split('/').filter((segment) => segment !== '' && segment !== '.')
  if (segments.length === 0 || segments.includes('..')) return undefined
  return segments.join('/')
}

/** Whether `path` resolves inside `root`. */
export function inside(root: string, path: string): boolean {
  const base = resolve(root)
  const target = resolve(path)
  return target === base || target.startsWith(base + sep)
}

/**
 * The file a project shows as its design: the one its metadata names, else `index.html`, else the single `.html` at the
 * project's root — the same order OpenDesign's own `get_project` resolves an entry with (`resolveProjectEntry` in
 * `apps/daemon/src/mcp.ts`).
 */
export function entryOf(files: readonly { path: string }[], declared?: unknown): string | null {
  if (typeof declared === 'string' && declared) return declared
  const index = files.find((file) => file.path === 'index.html')
  if (index) return index.path
  const rooted = files.filter(
    (file) => !file.path.includes('/') && file.path.toLowerCase().endsWith('.html'),
  )
  return rooted.length === 1 ? rooted[0].path : null
}

/** One file's manifest record. */
export function record(file: PulledFile): FileRecord {
  return {
    path: file.path,
    mime: file.mime,
    size: file.bytes.length,
    sha256: createHash('sha256').update(file.bytes).digest('hex'),
  }
}

/** What this pull adds, changes, leaves alone and removes, against the manifest it replaces. */
export function changes(before: Manifest | undefined, after: Manifest): ChangeSet {
  const previous = new Map((before?.files ?? []).map((file) => [file.path, file.sha256]))
  const added: string[] = []
  const changed: string[] = []
  const unchanged: string[] = []
  for (const file of after.files) {
    const hash = previous.get(file.path)
    if (hash === undefined) added.push(file.path)
    else if (hash === file.sha256) unchanged.push(file.path)
    else changed.push(file.path)
    previous.delete(file.path)
  }
  return { added, changed, removed: [...previous.keys()], unchanged: unchanged.length }
}

/** The manifest a design folder holds, or `undefined` when there is none yet or it cannot be read as one. */
export async function readManifest(dir: string): Promise<Manifest | undefined> {
  let text: string
  try {
    text = await readFile(join(dir, manifestName), 'utf8')
  } catch {
    // No manifest yet is the normal first pull; anything else the pull cannot act on here either.
    return undefined
  }
  try {
    const value = JSON.parse(text) as Manifest
    if (!value || typeof value !== 'object' || !Array.isArray(value.files)) return undefined
    if (typeof value.project?.id !== 'string') return undefined
    return value
  } catch {
    // A manifest written by something else is not this snapshot's; the pull replaces it.
    return undefined
  }
}

/**
 * The design folders under `root`, by project id. A folder whose manifest names another project does not stand in for
 * it: a pull picks a distinct folder instead (see `server.ts`).
 */
export async function pulled(root: string): Promise<Map<string, PulledDesign>> {
  const designs = new Map<string, PulledDesign>()
  let names: string[]
  try {
    names = (await readdir(root, { withFileTypes: true }))
      .filter((entry) => entry.isDirectory())
      .map((entry) => entry.name)
  } catch (error) {
    // No designs folder yet means nothing has been pulled.
    if ((error as NodeJS.ErrnoException).code === 'ENOENT') return designs
    throw error
  }
  for (const slug of names) {
    const manifest = await readManifest(join(root, slug))
    if (!manifest) continue
    designs.set(manifest.project.id, {
      dir: join(root, slug),
      slug,
      projectId: manifest.project.id,
      projectName: manifest.project.name,
      fetchedAt: manifest.fetchedAt,
      files: manifest.files.length,
    })
  }
  return designs
}

/**
 * Which of `project`'s files this pull writes, and which it leaves out: names that would escape the folder, files over
 * `maxFileBytes`, and files past `maxFiles` or `maxTotalBytes`.
 */
export function selectFiles(
  files: readonly { path: unknown; size?: number | null }[],
  limits = { maxFileBytes: 8 * 1024 * 1024, maxTotalBytes: 40 * 1024 * 1024, maxFiles: 400 },
): { wanted: { path: string; size: number | null }[]; skipped: SkippedFile[] } {
  const wanted: { path: string; size: number | null }[] = []
  const skipped: SkippedFile[] = []
  let total = 0
  for (const file of files) {
    const path = relativePath(file.path)
    if (!path) {
      skipped.push({
        path: String(file.path),
        reason: 'the name does not stay inside the design folder',
      })
      continue
    }
    if (typeof file.size === 'number' && file.size > limits.maxFileBytes) {
      skipped.push({ path, reason: `larger than ${limits.maxFileBytes / 1024 / 1024} MiB` })
      continue
    }
    if (wanted.length >= limits.maxFiles) {
      skipped.push({ path, reason: `past the first ${limits.maxFiles} files` })
      continue
    }
    if (total + (file.size ?? 0) > limits.maxTotalBytes) {
      skipped.push({
        path,
        reason: `past ${limits.maxTotalBytes / 1024 / 1024} MiB of design files`,
      })
      continue
    }
    total += file.size ?? 0
    wanted.push({ path, size: file.size ?? null })
  }
  return { wanted, skipped }
}

/**
 * Write a pull into `dir`, which becomes the snapshot: every file at its relative path, the manifest, the frame when
 * the daemon rendered one, and then the files the pull before it wrote and this one does not. Returns the absolute paths
 * written and the change against `before`.
 */
export async function writeBundle(
  dir: string,
  files: readonly PulledFile[],
  manifest: Manifest,
  before: Manifest | undefined,
  frame?: Buffer,
): Promise<{ written: string[]; change: ChangeSet }> {
  const written: string[] = []
  for (const file of files) {
    const path = relativePath(file.path)
    if (!path) continue
    const target = join(dir, path)
    if (!inside(dir, target)) continue
    await mkdir(dirname(target), { recursive: true })
    await writeFile(target, file.bytes)
    written.push(target)
  }
  if (frame) {
    await writeFile(join(dir, frameName), frame)
    written.push(join(dir, frameName))
  }
  await writeFile(join(dir, manifestName), `${JSON.stringify(manifest, null, 2)}\n`)
  written.push(join(dir, manifestName))
  const kept = new Set(manifest.files.map((file) => file.path))
  for (const file of before?.files ?? []) {
    if (kept.has(file.path)) continue
    const path = relativePath(file.path)
    if (!path) continue
    await rm(join(dir, path), { force: true })
  }
  return { written, change: changes(before, manifest) }
}
